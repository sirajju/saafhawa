'use client';

import React from 'react';
import { PlanSummary } from '@/lib/plan/types';
import { FallbackReason } from '@/lib/constants';
import { EQUIVALENCY_FACTORS } from '@/lib/impact/exposure-factors';
import { VEHICULAR_EMISSION_FACTORS } from '@/lib/impact/emission-factors';

interface TotalSavingsBannerProps {
  summary: PlanSummary;
  generationMethod?: 'gemini' | 'rule_based_fallback';
  fallbackReason?: FallbackReason;
  dailyQuotaResetTime?: string;
  onRetry?: () => void;
}

/**
 * Summary banner showcasing total inhaled PM2.5 dose avoided, equivalent cigarettes not smoked,
 * and household carbon emissions prevented.
 */
export function TotalSavingsBanner({
  summary,
  generationMethod = 'rule_based_fallback',
  fallbackReason,
  dailyQuotaResetTime,
  onRetry,
}: TotalSavingsBannerProps) {
  const dose = summary.totalPm25InhaledDoseAvoidedUg;
  const isDoseUnknown = summary.isExposureUnknown || dose === null;
  const co2Kg = summary.totalCo2EmissionsSavedKg;
  const pm25Grams = summary.totalPm25EmissionsSavedGrams;

  const cigaretteEquiv =
    !isDoseUnknown && dose > 0
      ? Math.round(dose / EQUIVALENCY_FACTORS.CIGARETTE_INHALED_PM25_DOSE_UG)
      : 0;

  const carKmEquiv = Math.round(
    (summary.totalCo2EmissionsSavedGrams || 0) / VEHICULAR_EMISSION_FACTORS.PETROL_CAR_CO2_G_PER_KM
  );

  return (
    <section className="card" aria-labelledby="impact-h">
      <div style={{ padding: '24px 28px 0' }}>
        <h2 id="impact-h">If you follow today&apos;s plan</h2>
      </div>

      <div className="impact">
        <div>
          <div className="eyebrow">Less smoke breathed in</div>
          <div className="stat num">
            {isDoseUnknown ? 'Unknown' : dose.toLocaleString()}
            <small>{isDoseUnknown ? '' : 'µg PM2.5'}</small>
          </div>
          <p>
            {isDoseUnknown
              ? 'Local PM2.5 measurements unavailable.'
              : cigaretteEquiv > 0
              ? `About ${cigaretteEquiv} cigarettes' worth across your family.`
              : 'Zero particulate exposure avoided under clean baseline air.'}
          </p>
        </div>

        <div>
          <div className="eyebrow">Soot kept out of the air</div>
          <div className="stat num">
            {pm25Grams.toFixed(2)}
            <small>g PM2.5</small>
          </div>
          <p>
            {pm25Grams > 0
              ? 'From skipping or swapping motorized vehicle trips.'
              : 'Defensive indoor routine today.'}
          </p>
        </div>

        <div>
          <div className="eyebrow">CO₂ avoided</div>
          <div className="stat num">
            {co2Kg.toFixed(1)}
            <small>kg</small>
          </div>
          <p>
            {carKmEquiv > 0
              ? `Like leaving the car parked for ${carKmEquiv} km.`
              : 'Zero tailpipe travel emitted.'}
          </p>
        </div>
      </div>

      <div className="foot-note" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: 8 }}>
        <span>Overlapping actions are adjusted, so the total can be less than the cards added together.</span>
        <span style={{ fontWeight: 500, display: 'inline-flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
          {generationMethod === 'gemini' ? (
            'Plan generated by Gemini AI'
          ) : fallbackReason === 'gemini_busy' ? (
            <>
              <span>Gemini is busy right now, so this plan was built by our rules. Try again in a minute.</span>
              {onRetry && (
                <button
                  type="button"
                  onClick={onRetry}
                  className="btn btn-sm"
                  style={{ padding: '2px 8px', fontSize: '12px', height: '24px' }}
                >
                  Retry
                </button>
              )}
            </>
          ) : fallbackReason === 'daily_quota_exhausted' ? (
            <span>Today&apos;s free Gemini limit is used up, so plans are built by our rules until {dailyQuotaResetTime || 'tomorrow'}.</span>
          ) : (
            'Plan generated by rule-based fallback'
          )}
        </span>
      </div>
    </section>
  );
}
